# --------------------------------------------------
# WHAT IS A VARIABLE?
# A variable is like a container or a box that stores data.
# When you write: name = "Harish", 
# 'name' is the variable name (label), and "Harish" is the value inside the box.
# --------------------------------------------------

# 1. Creating a String Variable (stores text)
name = "Harish"
print("Name:", name)

# 2. Creating an Integer Variable (stores whole numbers)
age = 25
print("Age:", age)

# 3. Creating a Float Variable (stores decimal numbers)
weight = 71.5
print("Weight:", weight)

# 4. Creating a Boolean Variable (stores True or False)
is_student = True
print("Is Student:", is_student)

# 5. Storing Multiple Variables
city = "Hyderabad"
course = "Python Full Stack"
print("City:", city)
print("Course:", course)

# 6. Changing (Updating) a Variable Value
# A variable value can change anytime!
age = 26
print("Updated Age:", age)

# 7. Doing Simple Math with Variables
a = 10
b = 20
total = a + b
print("Sum of a and b:", total)

# 8. Checking the Data Type of a Variable
print("Type of name:", type(name))
print("Type of age:", type(age))
print("Type of weight:", type(weight))
print("Type of is_student:", type(is_student))

